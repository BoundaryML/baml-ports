// Command gen generates BAML source for data tables that goldmark takes from
// Go's standard library (unicode range tables) or from embedded JSON data
// (HTML5 entities, Unicode case folding). BAML has no package-level
// constants, so every table becomes code: range tables become binary
// decision trees and maps become `match` expressions.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

type rng struct{ lo, hi int }

func tableRanges(tabs ...*unicode.RangeTable) []rng {
	var rs []rng
	for _, t := range tabs {
		for _, r := range t.R16 {
			for c := int(r.Lo); c <= int(r.Hi); c += int(r.Stride) {
				rs = append(rs, rng{c, c})
			}
		}
		for _, r := range t.R32 {
			for c := int(r.Lo); c <= int(r.Hi); c += int(r.Stride) {
				rs = append(rs, rng{c, c})
			}
		}
	}
	return merge(rs)
}

func merge(rs []rng) []rng {
	sort.Slice(rs, func(i, j int) bool { return rs[i].lo < rs[j].lo })
	var out []rng
	for _, r := range rs {
		if len(out) > 0 && r.lo <= out[len(out)-1].hi+1 {
			if r.hi > out[len(out)-1].hi {
				out[len(out)-1].hi = r.hi
			}
			continue
		}
		out = append(out, r)
	}
	return out
}

func tree(b *strings.Builder, rs []rng, indent string) {
	if len(rs) <= 4 {
		var conds []string
		for _, r := range rs {
			if r.lo == r.hi {
				conds = append(conds, fmt.Sprintf("r == 0x%X", r.lo))
			} else {
				conds = append(conds, fmt.Sprintf("(r >= 0x%X && r <= 0x%X)", r.lo, r.hi))
			}
		}
		if len(conds) == 0 {
			conds = []string{"false"}
		}
		fmt.Fprintf(b, "%s%s\n", indent, strings.Join(conds, " || "))
		return
	}
	mid := len(rs) / 2
	fmt.Fprintf(b, "%sif (r < 0x%X) {\n", indent, rs[mid].lo)
	tree(b, rs[:mid], indent+"    ")
	fmt.Fprintf(b, "%s} else {\n", indent)
	tree(b, rs[mid:], indent+"    ")
	fmt.Fprintf(b, "%s}\n", indent)
}

func rangeFunc(b *strings.Builder, name, doc string, rs []rng) {
	fmt.Fprintf(b, "/// %s\n/// Generated from %d merged code point ranges.\n", doc, len(rs))
	fmt.Fprintf(b, "function %s(r: int) -> bool {\n", name)
	tree(b, rs, "    ")
	fmt.Fprintf(b, "}\n\n")
}

func header(b *strings.Builder) {
	b.WriteString("// Code generated by tools/gen; DO NOT EDIT.\n\n")
}

func quote(s string) string {
	var sb strings.Builder
	sb.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			sb.WriteString(`\"`)
		case r == '\\':
			sb.WriteString(`\\`)
		case r == '\n':
			sb.WriteString(`\n`)
		case r == '\t':
			sb.WriteString(`\t`)
		case r == '\r':
			sb.WriteString(`\r`)
		case r < 0x20:
			// BAML string literals only support \n \t \r \0 \\ \" escapes.
			panic(fmt.Sprintf("unsupported control character %x", r))
		default:
			sb.WriteRune(r)
		}
	}
	sb.WriteByte('"')
	return sb.String()
}

func main() {
	goldmark := os.Args[1]
	out := os.Args[2]

	// unicode tables
	var b strings.Builder
	header(&b)
	rangeFunc(&b, "is_unicode_punct_or_symbol", "Port of `unicode.IsSymbol(r) || unicode.IsPunct(r)` (Unicode P and S categories).",
		tableRanges(unicode.P, unicode.S))
	rangeFunc(&b, "is_unicode_space", "Port of `unicode.IsSpace(r)`.",
		merge(append(tableRanges(unicode.White_Space), rng{0x85, 0x85}, rng{0xA0, 0xA0})))
	rangeFunc(&b, "is_east_asian_wide_script", "Port of `unicode.Is(unicode.Hiragana|Katakana|Han|Lm|Hangul, r)`.",
		tableRanges(unicode.Hiragana, unicode.Katakana, unicode.Han, unicode.Lm, unicode.Hangul))
	rangeFunc(&b, "is_unicode_punct", "Port of `unicode.IsPunct(r)` (Unicode P categories).",
		tableRanges(unicode.P))
	rangeFunc(&b, "is_unicode_hangul", "Port of `unicode.Is(unicode.Hangul, r)`.",
		tableRanges(unicode.Hangul))
	must(os.WriteFile(out+"/unicode_tables.gen.baml", []byte(b.String()), 0o644))

	// case folding
	var cfj struct {
		Data []struct {
			From string
			To   []string
		} `json:"data"`
	}
	{
		bs, err := os.ReadFile(goldmark + "/_tools/unicode-case-folding-map.json")
		must(err)
		must(json.Unmarshal(bs, &cfj))
	}
	type fold struct {
		from int
		to   []int
	}
	var folds []fold
	for _, d := range cfj.Data {
		from, err := strconv.ParseInt(d.From, 0, 32)
		must(err)
		var to []int
		for _, t := range d.To {
			v, err := strconv.ParseInt(t, 0, 32)
			must(err)
			to = append(to, int(v))
		}
		folds = append(folds, fold{int(from), to})
	}
	sort.Slice(folds, func(i, j int) bool { return folds[i].from < folds[j].from })
	b.Reset()
	header(&b)
	b.WriteString("/// Port of util/unicode_case_folding.go: the full Unicode case folding map.\n")
	b.WriteString("/// Returns the folded code points for `r`, or null if `r` has no folding.\n")
	b.WriteString("/// BAML has no package-level map constants, so the table is a binary\n/// decision tree over sorted keys ending in small `match` expressions.\n")
	b.WriteString("function unicode_case_folding(r: int) -> int[]? {\n")
	var foldTree func(fs []fold, indent string)
	foldTree = func(fs []fold, indent string) {
		if len(fs) <= 16 {
			fmt.Fprintf(&b, "%smatch (r) {\n", indent)
			for _, f := range fs {
				parts := []string{}
				for _, t := range f.to {
					parts = append(parts, fmt.Sprintf("0x%X", t))
				}
				fmt.Fprintf(&b, "%s    0x%X => [%s],\n", indent, f.from, strings.Join(parts, ", "))
			}
			fmt.Fprintf(&b, "%s    _ => null,\n%s}\n", indent, indent)
			return
		}
		mid := len(fs) / 2
		fmt.Fprintf(&b, "%sif (r < 0x%X) {\n", indent, fs[mid].from)
		foldTree(fs[:mid], indent+"    ")
		fmt.Fprintf(&b, "%s} else {\n", indent)
		foldTree(fs[mid:], indent+"    ")
		fmt.Fprintf(&b, "%s}\n", indent)
	}
	foldTree(folds, "    ")
	b.WriteString("}\n")
	must(os.WriteFile(out+"/unicode_case_folding.gen.baml", []byte(b.String()), 0o644))

	// html5 entities
	var entj struct {
		Data []struct {
			Name       string
			Characters []string
		} `json:"data"`
	}
	{
		bs, err := os.ReadFile(goldmark + "/_tools/html5entities.json")
		must(err)
		must(json.Unmarshal(bs, &entj))
	}
	ents := map[string]string{}
	byFirst := map[byte][]string{}
	for _, e := range entj.Data {
		var bs []byte
		for _, c := range e.Characters {
			v, err := strconv.ParseInt(c, 0, 32)
			must(err)
			bs = append(bs, byte(v))
		}
		ents[e.Name] = string(bs)
		byFirst[e.Name[0]] = append(byFirst[e.Name[0]], e.Name)
	}
	var firsts []int
	for c := range byFirst {
		firsts = append(firsts, int(c))
	}
	sort.Ints(firsts)
	b.Reset()
	header(&b)
	b.WriteString("/// Port of util/html5entities.gen.go: looks up the characters of the HTML5\n/// named character reference `name` (without the leading `&` and trailing `;`).\n")
	b.WriteString("/// Returns null when `name` is not a known entity.\n")
	b.WriteString("function html5_entity_characters(name: string) -> string? {\n")
	b.WriteString("    let first = name.code_point_at(0) ?? 0;\n")
	b.WriteString("    match (first) {\n")
	for _, c := range firsts {
		fmt.Fprintf(&b, "        %d => html5_entities_%c(name),\n", c, c)
	}
	b.WriteString("        _ => null,\n    }\n}\n\n")
	for _, c := range firsts {
		names := byFirst[byte(c)]
		sort.Strings(names)
		fmt.Fprintf(&b, "function html5_entities_%c(name: string) -> string? {\n    match (name) {\n", c)
		for _, n := range names {
			fmt.Fprintf(&b, "        %s => %s,\n", quote(n), quote(ents[n]))
		}
		b.WriteString("        _ => null,\n    }\n}\n\n")
	}
	must(os.WriteFile(out+"/html5entities.gen.baml", []byte(b.String()), 0o644))
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
